def can_use_stratify(y, test_size):
    counts = Counter(y)
    if len(counts) < 2:
        return False
    if min(counts.values()) < 2:
        return False
    n_test = math.ceil(len(y) * test_size)
    n_train = len(y) - n_test
    if n_test < len(counts) or n_train < len(counts):
        return False
    return True


def class_distribution(y_values, label_encoder):
    counter = Counter(y_values)
    distribution = {}
    for encoded_label, count in counter.items():
        class_name = label_encoder.inverse_transform([encoded_label])[0]
        distribution[class_name] = int(count)
    return dict(sorted(distribution.items(), key=lambda item: item[1], reverse=True))



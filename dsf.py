def normalize_required_columns(df):
    df.columns = [str(col).strip() for col in df.columns]
    lower_map = {col.lower().strip(): col for col in df.columns}
    rename_map = {}

    title_candidates = [
        "job_title", "job title", "title", "position", "job position",
        "nama pekerjaan", "pekerjaan"
    ]

    desc_candidates = [
        "job_description", "job description", "description", "desc",
        "job_desc", "job desc", "deskripsi", "deskripsi pekerjaan"
    ]

    for candidate in title_candidates:
        if candidate in lower_map:
            rename_map[lower_map[candidate]] = "job_title"
            break

    for candidate in desc_candidates:
        if candidate in lower_map:
            rename_map[lower_map[candidate]] = "job_description"
            break

    df = df.rename(columns=rename_map)

    required_cols = {"job_title", "job_description"}
    missing = required_cols - set(df.columns)

    if missing:
        print("Kolom yang ditemukan:")
        print(df.columns.tolist())
        raise ValueError(
            f"Kolom wajib tidak ditemukan: {missing}. "
            "Pastikan dataset punya kolom job_title dan job_description."
        )

    return df



def test_job_mapping(test_cases):
    print("\n" + "="*80)
    print("TESTING ULTRA GRANULAR JOB CATEGORY MAPPING")
    print("="*80)

    correct = 0
    total = len(test_cases)
    results = []

    for i, case in enumerate(test_cases, 1):
        row = {
            "job_title": case.get("title", ""),
            "job_description": case.get("description", "")
        }

        predicted = map_job_category(row)
        expected = case.get("expected_category", None)

        is_correct = (predicted == expected)
        if is_correct:
            correct += 1
            status = "✓ CORRECT"
        else:
            status = "✗ WRONG"

        results.append({
            "no": i,
            "title": case.get("title", ""),
            "expected": expected,
            "predicted": predicted,
            "status": status
        })

        print(f"\n{i}. {status}")
        print(f"   Title: {case.get('title', '')}")
        print(f"   Expected: {expected}")
        print(f"   Predicted: {predicted}")

    accuracy = (correct / total * 100) if total > 0 else 0

    print("\n" + "="*80)
    print(f"MAPPING ACCURACY: {correct}/{total} ({accuracy:.2f}%)")
    print("="*80)

    return pd.DataFrame(results)



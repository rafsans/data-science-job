def run_pipeline_csv(input_file, output_dir, test_size=0.2, random_state=42):
    os.makedirs(output_dir, exist_ok=True)

    df_raw = read_csv_safe(input_file)
    df_raw = normalize_required_columns(df_raw)

    print("Kolom yang ditemukan:")
    print(df_raw.columns.tolist())

    total_before = len(df_raw)

    df_raw["job_title"] = df_raw["job_title"].fillna("").astype(str).str.strip()
    df_raw["job_description"] = df_raw["job_description"].fillna("").astype(str)

    empty_title_mask = (
        (df_raw["job_title"] == "") |
        (df_raw["job_title"].str.lower() == "nan")
    )

    removed_rows_empty_job_title = int(empty_title_mask.sum())
    df_raw = df_raw[~empty_title_mask].reset_index(drop=True)

    invalid_title_mask = df_raw["job_title"].str.contains(
        r"\bmctf\b|exhibition centre|career fair",
        case=False,
        na=False
    )

    removed_invalid_titles = int(invalid_title_mask.sum())
    df_raw = df_raw[~invalid_title_mask].reset_index(drop=True)

    total_after_title_filter = len(df_raw)

    print(f"\n[INFO] Jumlah data awal: {total_before}")
    print(f"[INFO] Dibuang karena job_title kosong: {removed_rows_empty_job_title}")
    print(f"[INFO] Dibuang karena bukan job title valid: {removed_invalid_titles}")
    print(f"[INFO] Setelah filter awal: {total_after_title_filter}")

    if len(df_raw) == 0:
        raise ValueError("Dataset kosong setelah menghapus job_title kosong / tidak valid.")

    df_raw["clean_text"] = (
        df_raw["job_title"].fillna("").astype(str) + " " +
        df_raw["job_description"].fillna("").astype(str)
    ).apply(clean_text)

    df_raw["job_title_normalized"] = df_raw["job_title"].apply(clean_text)

    print("\n[INFO] Mulai mapping job_category...")
    df_raw["job_category"] = df_raw.apply(map_job_category, axis=1)

    unmapped_rows = df_raw[df_raw["job_category"].isna()].copy()
    mapped_rows = df_raw[df_raw["job_category"].notna()].copy()

    unmapped_rows[["job_title", "job_description"]].to_csv(
        os.path.join(output_dir, "cek_unmapped_rows.csv"),
        index=False,
        encoding="utf-8"
    )

    print("\n[INFO] Jumlah data belum ter-mapping:", len(unmapped_rows))
    print("[INFO] Persentase belum ter-mapping:", round(len(unmapped_rows) / len(df_raw) * 100, 2), "%")

    print("\n[INFO] Top 50 job_title yang belum ter-mapping:")
    if len(unmapped_rows) > 0:
        unmapped_titles = unmapped_rows["job_title"].value_counts().head(50)
        print(unmapped_titles)
        unmapped_titles.to_csv(
            os.path.join(output_dir, "top_unmapped_titles.csv"),
            header=["count"],
            encoding="utf-8"
        )
    else:
        print("Tidak ada data unmapped.")

    df = mapped_rows.reset_index(drop=True)

    if len(df) == 0:
        raise ValueError("Tidak ada data yang berhasil dipetakan.")

    print("\n[INFO] Jumlah data yang dipakai training:", len(df))
    print("[INFO] Jumlah data yang tidak dipakai training:", len(unmapped_rows))

    print("\n[INFO] Distribusi job_category:")
    category_dist = df["job_category"].value_counts()
    print(category_dist)

    print("\n[INFO] Persentase job_category:")
    category_pct = (df["job_category"].value_counts(normalize=True) * 100).round(2)
    print(category_pct)

    pd.DataFrame({
        "job_category": category_dist.index,
        "count": category_dist.values,
        "percentage": category_pct.values
    }).to_csv(
        os.path.join(output_dir, "category_distribution.csv"),
        index=False,
        encoding="utf-8"
    )

    text_for_skills = (
        df["job_title"].fillna("").astype(str) + " " +
        df["job_description"].fillna("").astype(str) + " " +
        df["clean_text"].fillna("").astype(str)
    )

    print("\n[INFO] Extracting skills...")
    df["skills_extracted"] = text_for_skills.apply(extract_skills)

    label_encoder = LabelEncoder()
    y = label_encoder.fit_transform(df["job_category"])

    df["job_category_encoded"] = y

    indices = np.arange(len(df))
    stratify = y if can_use_stratify(y, test_size) else None

    print("\n[INFO] Splitting data...")
    train_idx, test_idx = train_test_split(
        indices,
        test_size=test_size,
        random_state=random_state,
        stratify=stratify
    )

    df["split"] = "test"
    df.loc[train_idx, "split"] = "train"

    train_texts = df.loc[train_idx, "clean_text"].fillna("").astype(str).tolist()
    test_texts = df.loc[test_idx, "clean_text"].fillna("").astype(str).tolist()
    all_texts = df["clean_text"].fillna("").astype(str).tolist()

    train_texts = [text if text.strip() else "emptytext" for text in train_texts]
    test_texts = [text if text.strip() else "emptytext" for text in test_texts]
    all_texts = [text if text.strip() else "emptytext" for text in all_texts]

    print("\n[INFO] Vectorizing with TF-IDF...")
    vectorizer = TfidfVectorizer(
        max_features=8000,
        ngram_range=(1, 2),
        min_df=1,
        sublinear_tf=True
    )

    X_train = vectorizer.fit_transform(train_texts)
    X_test = vectorizer.transform(test_texts)
    X_all = vectorizer.transform(all_texts)

    y_train = y[train_idx]
    y_test = y[test_idx]

    df_output = df.copy()

    df_output["skills_extracted"] = df_output["skills_extracted"].apply(
        lambda x: ", ".join(x) if len(x) > 0 else "[]"
    )

    print("\n[INFO] Saving processed data...")
    df_output.to_csv(os.path.join(output_dir, "processed_data.csv"), index=False, encoding="utf-8")
    df_output.to_csv(os.path.join(output_dir, "processed_data_category.csv"), index=False, encoding="utf-8")

    sparse.save_npz(os.path.join(output_dir, "X_tfidf_all.npz"), X_all)
    sparse.save_npz(os.path.join(output_dir, "X_train_tfidf.npz"), X_train)
    sparse.save_npz(os.path.join(output_dir, "X_test_tfidf.npz"), X_test)

    np.save(os.path.join(output_dir, "y_all.npy"), y)
    np.save(os.path.join(output_dir, "y_train.npy"), y_train)
    np.save(os.path.join(output_dir, "y_test.npy"), y_test)

    joblib.dump(vectorizer, os.path.join(output_dir, "tfidf_vectorizer.pkl"))
    joblib.dump(label_encoder, os.path.join(output_dir, "label_encoder_category.pkl"))

    label_mapping = pd.DataFrame({
        "job_category": label_encoder.classes_,
        "job_category_encoded": range(len(label_encoder.classes_))
    })

    label_mapping.to_csv(
        os.path.join(output_dir, "job_category_label_mapping.csv"),
        index=False,
        encoding="utf-8"
    )

    split_info = pd.DataFrame({
        "row_index_zero_based": np.arange(len(df)),
        "split": df["split"]
    })

    split_info.to_csv(
        os.path.join(output_dir, "train_test_indices.csv"),
        index=False,
        encoding="utf-8"
    )

    summary = {
        "input_file": input_file,
        "output_dir": output_dir,
        "total_rows_before_filter": int(total_before),
        "removed_rows_empty_job_title": int(removed_rows_empty_job_title),
        "removed_invalid_titles": int(removed_invalid_titles),
        "total_rows_after_initial_filter": int(total_after_title_filter),
        "mapped_rows_used_for_training": int(len(df)),
        "unmapped_rows_not_used_for_training": int(len(unmapped_rows)),
        "unmapped_percentage_from_clean_data": float(round(len(unmapped_rows) / len(df_raw) * 100, 2)),
        "target_column": "job_category",
        "category_granularity": "ULTRA GRANULAR - Categories with / split into separate classes",
        "total_classes": int(len(label_encoder.classes_)),
        "label_classes": label_encoder.classes_.tolist(),
        "stratify_used": bool(stratify is not None),
        "tfidf_all_shape": list(X_all.shape),
        "train_shape": list(X_train.shape),
        "test_shape": list(X_test.shape),
        "train_class_distribution": class_distribution(y_train, label_encoder),
        "test_class_distribution": class_distribution(y_test, label_encoder),
        "note": (
            "ULTRA GRANULAR VERSION: Categories with / are split into more specific classes. "
            "Examples: Data Science / AI → Data Science + AI/ML Engineering. "
            "Data Analyst / BI → Data Analyst + Business Intelligence. "
            "This provides more precise categorization for specialized roles."
        )
    }

    with open(os.path.join(output_dir, "summary.json"), "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)

    zip_path = output_dir + ".zip"

    if os.path.exists(zip_path):
        os.remove(zip_path)

    shutil.make_archive(output_dir, "zip", output_dir)

    print("\n==============================")
    print("PIPELINE SELESAI")
    print("==============================")
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    print("\nFolder hasil:", output_dir)
    print("ZIP hasil:", zip_path)

    return df_output, summary


